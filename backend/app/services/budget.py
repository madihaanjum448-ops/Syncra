from ..models.budget import BudgetRequest
from typing import List, Dict

# Placeholder rule‑based recommendation engine
def recommend_actions(request: BudgetRequest) -> List[Dict]:
    """Return a list of recommendation dicts.
    Each dict contains:
      - action: one of "approve", "reduce", "revision", "reject"
      - reason: short explanation (normally generated by LLM, here static)
    The rules are simple examples:
      * If any category exceeds a hard ceiling, suggest reduction.
      * If total > 5000, suggest revision.
    """
    recommendations = []
    # Example ceilings per category
    ceilings = {
        "venue": 2000,
        "food": 1000,
        "prizes": 800,
        "marketing": 500,
        "equipment": 700,
        "honorarium": 600,
        "misc": 300,
    }
    for item in request.items:
        ceiling = ceilings.get(item.category, 0)
        if item.amount > ceiling:
            recommendations.append({
                "action": "reduce",
                "reason": f"{item.category.title()} exceeds ceiling of ${ceiling:.0f}",
            })
    if request.total_amount > 5000:
        recommendations.append({
            "action": "revision",
            "reason": "Total budget exceeds $5,000, consider trimming items",
        })
    if not recommendations:
        recommendations.append({"action": "approve", "reason": "Budget looks within limits"})
    return recommendations
